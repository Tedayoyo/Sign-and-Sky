// Builds src/data/library.json: the published signs, exactly as the seed SQL stores them.
// The website uses it when the database cannot be reached, so the Ask page, the sign library
// and the results always work. Re-run after changing scripts/build_seed.py:
//   npm run build-library
import fs from "node:fs";
import path from "node:path";
import { startDb, stopDb } from "../tests/helpers";
import { publishedSigns } from "../src/lib/records";

async function main() {
  delete process.env.TEST_DATABASE_URL; // always a fresh in-process database
  await startDb();
  const signs = await publishedSigns();
  const out = signs.map((s) => ({
    ...s,
    id: `builtin-${s.record_number}`,
    evaluations: s.evaluations.map((e, i) => ({ ...e, id: `builtin-${s.record_number}-${i}`, created_at: "2025-12-31T00:00:00.000Z" })),
  }));
  const file = path.join(process.cwd(), "src", "data", "library.json");
  fs.writeFileSync(file, JSON.stringify({ note: "Generated by scripts/build-library.ts from supabase/seed. Do not edit by hand.", signs: out }, null, 1) + "\n");
  console.log(`${out.length} signs written to src/data/library.json`);
  await stopDb();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
